async function seedHashtags() {
  console.log(`🌱 Seeding ${hashtagsSeedData.length} curated hashtags into Supabase...`);
  try {
    const { data, error } = await supabaseAdmin
      .from('hashtags')
      .upsert(hashtagsSeedData, { onConflict: 'tag' })
      .select();

    if (error) {
      console.error('Seed error:', error.message);
      process.exit(1);
    }

    console.log(`✅ Successfully seeded ${data?.length || hashtagsSeedData.length} hashtags across 8 niches!`);
    process.exit(0);
  } catch (err) {
    console.error('Unexpected seed failure:', err);
    process.exit(1);
  }
}

